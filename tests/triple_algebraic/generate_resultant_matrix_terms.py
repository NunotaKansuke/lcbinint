"""Generate the exact integer contraction from sextic products to real Bezout entries."""
import argparse
from collections import defaultdict
from pathlib import Path
import random

WEIGHT = [2, 3, 4, 3, 2]
VALUATION = [2, 1, 0, 0, 0]
PHASE = [[-1] * 5 for _ in range(5)]
for row, column in [(0, 0), (4, 0), (1, 1), (3, 1), (2, 2)]:
    PHASE[row][column] = 0
PHASE[0][4] = PHASE[1][3] = 1
PHASE[4][4] = PHASE[3][3] = 3


def generate():
    bezout = [[defaultdict(int) for _ in range(5)] for _ in range(5)]
    for i in range(1, 6):
        for j in range(i):
            # B(Q', 6Q-zQ'): each coefficient is a product of two Q entries.
            terms = [(tuple(sorted((j, i + 1))), (i + 1) * (6 - j)),
                     (tuple(sorted((j + 1, i))), -(j + 1) * (6 - i))]
            for k in range(i - j):
                for key, coefficient in terms:
                    bezout[i - 1 - k][j + k][key] += coefficient
    entries = []
    for i in range(5):
        for j in range(i, 5):
            terms = defaultdict(int)
            for k in range(5):
                if PHASE[k][i] < 0:
                    continue
                for l in range(5):
                    if PHASE[l][j] < 0:
                        continue
                    phase = (PHASE[k][i] + PHASE[l][j]) % 4
                    for (a, b), coefficient in bezout[k][l].items():
                        key = a, b, VALUATION[k] + VALUATION[l], phase % 2
                        terms[key] += coefficient * (1 if phase in (0, 3) else -1)
            entries.append((i, j, [(*key, c) for key, c in sorted(terms.items()) if c]))
    return entries


def render(entries):
    lines = ['#pragma once',
             'namespace lcbinint::algebraic_boundary::triple::resultant_detail {',
             '// Generated by tests/triple_algebraic/generate_resultant_matrix_terms.py.',
             'struct MatrixTerm {int a,b,shift,imaginary,coefficient;};',
             'inline constexpr MatrixTerm matrix_terms[] = {']
    starts = [0]
    for _, _, terms in entries:
        lines.extend(' {' + ','.join(map(str, term)) + '},' for term in terms)
        starts.append(starts[-1] + len(terms))
    lines += ['};', 'inline constexpr int matrix_term_starts[16] = {' +
              ','.join(map(str, starts)) + '};', '', '}']
    return '\n'.join(lines) + '\n'


def exact_check(entries):
    """Compare with the unsimplified construction using Gaussian integers."""
    def add(a, b):
        return a[0] + b[0], a[1] + b[1]

    def scale(a, c):
        return a[0] * c, a[1] * c

    def multiply(a, b):
        result = [(0, 0)] * 9
        for i, x in enumerate(a):
            for j, y in enumerate(b):
                result[i + j] = add(result[i + j],
                                    (x[0] * y[0] - x[1] * y[1],
                                     x[0] * y[1] + x[1] * y[0]))
        return result

    rng = random.Random(814693)
    checks = 0
    for _ in range(50):
        q = [[(rng.randrange(-9, 10), rng.randrange(-9, 10))
              for _ in range(5)] for _ in range(7)]
        u = [[scale(x, i + 1) for x in q[i + 1]] for i in range(6)]
        v = [[scale(x, 6 - i) for x in q[i]] for i in range(6)]
        bezout = [[[(0, 0)] * 9 for _ in range(5)] for _ in range(5)]
        for i in range(1, 6):
            for j in range(i):
                plus, minus = multiply(u[i], v[j]), multiply(u[j], v[i])
                difference = [add(x, scale(y, -1)) for x, y in zip(plus, minus)]
                for k in range(i - j):
                    cell = bezout[i - 1 - k][j + k]
                    for n in range(9):
                        cell[n] = add(cell[n], difference[n])
        for i, j, terms in entries:
            products = {(a, b): multiply(q[a], q[b]) for a, b, *_ in terms}
            for n in range(WEIGHT[i] + WEIGHT[j] + 1):
                expected = 0
                for k in range(5):
                    if PHASE[k][i] < 0:
                        continue
                    for l in range(5):
                        if PHASE[l][j] < 0:
                            continue
                        phase = (PHASE[k][i] + PHASE[l][j]) % 4
                        z = bezout[k][l][n + VALUATION[k] + VALUATION[l]]
                        expected += z[phase % 2] * (1 if phase in (0, 3) else -1)
                actual = sum(c * products[a, b][n + shift][imaginary]
                             for a, b, shift, imaginary, c in terms)
                assert actual == expected, (i, j, n, actual, expected)
                checks += 1
    return checks


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    entries = generate()
    checks = exact_check(entries)
    path = Path(__file__).resolve().parents[2] / 'src/lcbinint/magnification/algebraic_boundary/triple/resultant_matrix_terms.hpp'
    generated = render(entries)
    if args.check:
        assert path.read_text() == generated, f'{path} is stale'
    else:
        path.write_text(generated)
    print(f'PASS: {checks} exact Gaussian-integer matrix coefficients; 96 terms, 24 products')
