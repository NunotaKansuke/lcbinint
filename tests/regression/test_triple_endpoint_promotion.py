@pytest.mark.parametrize("params,epochs,rtol", CASES)
def test_unresolved_geometry_endpoints_recover(params,epochs,rtol):
    model=lc.LightCurve(lens="triple",param_type="vbm",options=lc.Options(
        finite_source_tol=0.,finite_source_reltol=rtol))
    value=model.magnification(epochs,params)
    tangent=model.magnification(epochs,params,with_gradient=True)
    assert np.all(value.status==0)
    assert np.all(tangent.status==0)
    assert np.all(tangent.gradient_valid)
    assert np.all(np.isfinite(tangent.gradients))
    np.testing.assert_allclose(tangent.magnifications,value.magnifications,rtol=2*rtol)


def test_duplicate_stationary_events_do_not_create_roundoff_width_panels():
    # Independent VBM MultiPoly/NoPoly at relative 1e-6 agree at this epoch.
    params = {'t0': 0.02202591926726627,
     'u0': -0.4992885592945948,
     'tE': 1.0349456414850233,
     'alpha': 0.5047686393794271,
     's': 0.9158646546810919,
     'q': 2.973559025618435,
     'q2': 0.008467094758366525,
     'sep2': 0.48970767368109713,
     'ang': -0.6211369068841304,
     'rho': 0.002230527954027309}
    epoch = -0.3660786962896175
    model = lc.LightCurve(lens="triple",param_type="vbm",ld_c=.5,
        options=lc.Options(finite_source_tol=0.,finite_source_reltol=1e-4))
    result = model.magnification([epoch],params,with_gradient=True)
    assert result.status.tolist() == [0]
    assert result.gradient_valid.tolist() == [True]
    np.testing.assert_allclose(result.magnifications,[7.9454531774167],rtol=1e-4)
