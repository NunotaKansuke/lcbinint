@pytest.mark.parametrize("case,params,times,limb,rtol", CASES)
def test_repaired_contact_packets(case, params, times, limb, rtol):
    model = lc.LightCurve(lens="triple", param_type="vbm", ld_c=limb,
        options=lc.Options(finite_source_tol=0., finite_source_reltol=rtol))
    scalar = model.info(times, params, with_gradient=False)
    tangent = model.info(times, params, with_gradient=True)
    assert not np.any(scalar.status), case
    assert not np.any(tangent.status), case
    assert np.all(tangent.gradient_valid), case
    assert np.all(np.isfinite(tangent.gradients)), case
    np.testing.assert_allclose(tangent.magnifications, scalar.magnifications,
                               rtol=rtol, atol=0.)


