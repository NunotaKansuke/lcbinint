from collections import defaultdict
from pathlib import Path
import json
B=[[defaultdict(int) for _ in range(5)] for _ in range(5)]
for i in range(1,6):
 for j in range(i):
  terms=[((j,i+1),(i+1)*(6-j)),(tuple(sorted((j+1,i))),-(j+1)*(6-i))]
  for k in range(i-j):
   for key,c in terms:B[i-1-k][j+k][key]+=c
phase=[[-1]*5 for _ in range(5)]
for k,j in [(0,0),(4,0),(1,1),(3,1),(2,2)]:phase[k][j]=0
phase[0][4]=phase[1][3]=1;phase[4][4]=phase[3][3]=3
val=[2,1,0,0,0];out=[]
for i in range(5):
 for j in range(i,5):
  d=defaultdict(int)
  for k in range(5):
   if phase[k][i]<0:continue
   for l in range(5):
    if phase[l][j]<0:continue
    ph=(phase[k][i]+phase[l][j])%4
    for (a,b),c in B[k][l].items():d[a,b,val[k]+val[l],ph%2]+=c*(1 if ph in (0,3) else -1)
  out.append(dict(i=i,j=j,terms=[[*key,c] for key,c in sorted(d.items()) if c]))
p=Path(__file__).resolve().parent
(p/'terms.json').write_text(json.dumps(out,indent=2)+'\n')
print('terms',sum(len(x['terms']) for x in out),'products',len({tuple(t[:2]) for x in out for t in x['terms']}))
lines=['// Generated by generate_terms.py from the Bezout identity and real congruence.','struct MatrixTerm {int a,b,shift,imaginary,coefficient;};','inline constexpr MatrixTerm matrix_terms[] = {']
starts=[0]
for x in out:
 for t in x['terms']:lines.append(' {'+','.join(map(str,t))+'},')
 starts.append(starts[-1]+len(x['terms']))
lines+=['};','inline constexpr int matrix_term_starts[16] = {'+','.join(map(str,starts))+'};']
(p/'matrix_terms.hpp').write_text('\n'.join(lines)+'\n')
